package remediation

import (
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/abhiraj-ku/finops/internal/collector"
)

func CleanupScript(resources []collector.OrphanResource, region string, filename string) error {
	if len(resources) == 0 {
		return nil
	}

	timestamp := time.Now().Format("2006-01-02-150405")

	var sb strings.Builder

	sb.WriteString("#!/bin/bash\n")
	sb.WriteString("# AutoGenerated by finops\n")
	sb.WriteString(fmt.Sprintf("# Run Date: %s | Region: %s\n", time.Now().Format(time.RFC3339), region))
	sb.WriteString("set -e # Exit immediately if a command exits with a non-zero status.\n\n")

	for _, r := range resources {
		sb.WriteString(fmt.Sprintf("# --- Resource: %s | Creator: %s | Savings: $%.2f/mo ---\n", r.ID, r.Creator, r.EstimatedMo))

		if r.Type == collector.TypeEBSVolume {
			// EBS requires manually creating a snapshot before deleting
			snapName := fmt.Sprintf("ghost-backup-%s-%s", r.ID, timestamp)
			sb.WriteString("echo \"Backing up EBS volume " + r.ID + "...\"\n")
			sb.WriteString(fmt.Sprintf("SNAPSHOT_ID=$(aws ec2 create-snapshot --region %s --volume-id %s --description \"FinOps-Ghost pre-delete backup\" --tag-specifications 'ResourceType=snapshot,Tags=[{Key=Name,Value=%s}]' --query 'SnapshotId' --output text)\n", region, r.ID, snapName))

			sb.WriteString("echo \"Snapshot $SNAPSHOT_ID created. Deleting volume...\"\n")
			sb.WriteString(fmt.Sprintf("aws ec2 delete-volume --region %s --volume-id %s\n\n", region, r.ID))
		}

		if r.Type == collector.TypeRDSInstance {
			// RDS has a built-in flag to take a final snapshot on deletion
			snapID := fmt.Sprintf("%s-final-snap-%s", r.ID, timestamp)
			sb.WriteString("echo \"Deleting RDS instance " + r.ID + " with a final snapshot...\"\n")
			sb.WriteString(fmt.Sprintf("aws rds delete-db-instance --region %s --db-instance-identifier %s --skip-final-snapshot false --final-db-snapshot-identifier %s\n\n", region, r.ID, snapID))
		}
	}

	sb.WriteString("echo \"Cleanup complete.\"\n")

	err := os.WriteFile(filename, []byte(sb.String()), 0755)
	if err != nil {
		return fmt.Errorf("failed to writer the remediation script: %w", err)
	}

	return nil

}
